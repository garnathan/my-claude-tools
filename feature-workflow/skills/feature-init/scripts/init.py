#!/usr/bin/env python3
"""Initialize feature-workflow directory structure and config.

Usage:
    python3 init.py [project-root] [--prefix PREFIX] [--target TARGET]
                                   [--review-mode MODE] [--provider PROVIDER]
    python3 init.py [project-root] --update    # re-sync .gitignore only

Creates (init mode):
    docs/features/
    docs/features/DASHBOARD.md   (initial template)
    .feature-workflow.yml        (branch + review config — new two-axis schema)
    .gitignore entry for the auto-generated DASHBOARD.md (and untracks it)

This port deliberately does NOT touch CI: no GitHub Actions workflow, no API-key
secret upload. The reviewer is a local subagent by default (review.mode=internal),
which needs no CI. To wire an external CI reviewer later, see
skills/shared/review-channel.md (the `external` mode is a documented extension).
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path


INITIAL_DASHBOARD = """# Feature Dashboard

*Auto-generated by hooks. Do not edit directly.*

## In Progress

*No features in progress*

## Backlog

*No features in backlog. Use `/feature-capture` to add one.*

## Completed

*No completed features*
"""

CONFIG_TEMPLATE = """# Feature workflow configuration
# Written by /feature-init — edit anytime to change settings.

branch:
  prefix: "{prefix}"      # Branch naming: <prefix><feature-id>
  target: "{target}"      # Base branch for PRs and merges

review:
  mode: "{mode}"          # internal | external | skip  (WHO reviews — default: internal, a local subagent)
  provider: "{provider}"  # github | bitbucket | none   (WHERE the PR + comments live)
"""


def setup_dashboard_gitignore(project_root: Path) -> None:
    """Add DASHBOARD.md to .gitignore and untrack it if currently tracked.

    DASHBOARD.md is 100% derived from feature directories — the PostToolUse hook
    regenerates it locally, and skills can render it on demand via
    `run_dashboard.py --stdout`. So it doesn't need to be committed.
    """
    gitignore_path = project_root / ".gitignore"
    marker = "docs/features/DASHBOARD.md"
    existing = gitignore_path.read_text() if gitignore_path.exists() else ""

    if marker not in existing:
        entry = "\n# Auto-generated locally by feature-workflow hooks — not committed\ndocs/features/DASHBOARD.md\n"
        if existing and not existing.endswith("\n"):
            entry = "\n" + entry
        with open(gitignore_path, "a") as f:
            f.write(entry)
        print("Added DASHBOARD.md to .gitignore")
    else:
        print(".gitignore already has DASHBOARD.md — skipped")

    # Untrack if currently tracked (best-effort; harmless if not a git repo).
    try:
        subprocess.run(
            ["git", "rm", "--cached", "docs/features/DASHBOARD.md"],
            capture_output=True, text=True, cwd=project_root,
        )
    except FileNotFoundError:
        pass


def update_mode(project_root: Path) -> int:
    """Re-sync the .gitignore entry. (No CI files to refresh in this port.)"""
    config_path = project_root / ".feature-workflow.yml"
    if not config_path.exists():
        print("ERROR: No .feature-workflow.yml found. Run /feature-init first.")
        return 1
    setup_dashboard_gitignore(project_root)
    print("")
    print("Update complete. (This port has no CI files to refresh — the reviewer is local.)")
    print("To wire an external CI reviewer, see skills/shared/review-channel.md.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("project_root", nargs="?", default=".")
    parser.add_argument("--prefix", default="feature/")
    parser.add_argument("--target", default="dev")
    parser.add_argument("--review-mode", dest="mode", default="internal",
                        choices=["internal", "external", "skip"])
    parser.add_argument("--provider", default="github",
                        choices=["github", "bitbucket", "none"])
    parser.add_argument("--update", action="store_true",
                        help="Re-sync the DASHBOARD.md .gitignore entry; don't touch config.")
    args = parser.parse_args()

    project_root = Path(args.project_root).resolve()

    if args.update:
        return update_mode(project_root)

    features_dir = project_root / "docs" / "features"
    config_path = project_root / ".feature-workflow.yml"

    if features_dir.is_dir():
        feature_count = sum(1 for p in features_dir.iterdir() if p.is_dir())
        print(f"docs/features/ already exists ({feature_count} features)")
    else:
        features_dir.mkdir(parents=True, exist_ok=True)
        (features_dir / "DASHBOARD.md").write_text(INITIAL_DASHBOARD)
        print("Created docs/features/ with DASHBOARD.md")

    config_content = CONFIG_TEMPLATE.format(
        prefix=args.prefix, target=args.target, mode=args.mode, provider=args.provider,
    )
    print("Updating .feature-workflow.yml" if config_path.exists() else "Creating .feature-workflow.yml")
    config_path.write_text(config_content)

    setup_dashboard_gitignore(project_root)

    print("")
    print("Feature workflow initialized!")
    print("")
    print(f"  Branch prefix:   {args.prefix}")
    print(f"  Target branch:   {args.target}")
    print(f"  Review mode:     {args.mode}")
    print(f"  Review provider: {args.provider}")
    print(f"  Branches:        {args.prefix}<feature-id>  →  {args.target}")
    print("")
    if args.mode == "internal":
        print("  Reviews run locally via a Claude subagent — no CI or API keys needed.")
    elif args.mode == "external":
        print("  Review mode is 'external' but no CI reviewer is wired yet — see")
        print("  skills/shared/review-channel.md. Until then it falls back to a local review.")
    print("")
    print("  Next: /feature-capture to create your first feature.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
